import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const bundlePath = resolve(root, "fixtures/protocol/v1/schema-bundle.json");
const outputPath = resolve(root, "sdk/src/generated/protocol.ts");
const check = process.argv.includes("--check");

const bundle = JSON.parse(readFileSync(bundlePath, "utf8"));
const schemas = bundle.schemas;
const catalog = bundle.fixtures.rpc_catalog;

if (!catalog || catalog.protocol !== "babel.rpc.v1") {
  throw new Error("schema bundle is missing the babel.rpc.v1 catalog fixture");
}

const schemaNames = Object.keys(schemas).sort();
const rootTypeNames = new Map(schemaNames.map((name) => [name, typeName(name)]));
const output = [
  "// Generated by sdk/scripts/generate-protocol.mjs from fixtures/protocol/v1/schema-bundle.json.",
  "// Do not edit by hand.",
  "",
  "export type JsonValue = null | boolean | number | string | JsonValue[] | { readonly [key: string]: JsonValue };",
  "",
  ...schemaNames.flatMap((schemaName) => renderRoot(schemaName, schemas[schemaName])),
  "export type RpcError = RpcRpcError;",
  "export type RpcRequestEnvelope = RpcRpcRequestEnvelope;",
  "export type RpcResponseEnvelope = RpcRpcResponseEnvelope;",
  "",
  renderProtocolTypes(),
  `export const protocol = ${JSON.stringify(bundle.protocol)} as const;`,
  `export const schemaBundleVersion = ${JSON.stringify(bundle.version)} as const;`,
  `export const rpcCatalog = ${JSON.stringify(catalog, null, 2)} as const;`,
  "",
  "export type RpcMethodName = typeof rpcCatalog.methods[number][\"method\"];",
  "export type RpcMethodDefinition<M extends RpcMethodName = RpcMethodName> = Extract<typeof rpcCatalog.methods[number], { readonly method: M }>",
  "export type RpcInputName<M extends RpcMethodName> = RpcMethodDefinition<M>[\"input\"] & keyof ProtocolTypes;",
  "export type RpcOutputName<M extends RpcMethodName> = RpcMethodDefinition<M>[\"output\"] & keyof ProtocolTypes;",
  "export type RpcInput<M extends RpcMethodName> = ProtocolTypes[RpcInputName<M>];",
  "export type RpcOutput<M extends RpcMethodName> = ProtocolTypes[RpcOutputName<M>];",
  "export type RpcIdempotency<M extends RpcMethodName> = RpcMethodDefinition<M>[\"idempotency\"];",
  "",
].join("\n");

if (check) {
  const current = readFileSync(outputPath, "utf8");
  if (current !== output) {
    throw new Error(`${outputPath} is stale; run npm --prefix sdk run generate`);
  }
} else {
  writeFileSync(outputPath, output);
}

function renderRoot(schemaName, schema) {
  const defs = schema.$defs ?? {};
  const rootName = rootTypeNames.get(schemaName);
  return [
    ...Object.keys(defs).sort().map((defName) => {
      const rendered = tsType(defs[defName], schemaName);
      return `export type ${defTypeName(schemaName, defName)} = ${rendered};`;
    }),
    `export type ${rootName} = ${tsType(schema, schemaName)};`,
    "",
  ];
}

function renderProtocolTypes() {
  const entries = schemaNames
    .map((name) => `  readonly ${JSON.stringify(name)}: ${rootTypeNames.get(name)};`)
    .join("\n");
  return `export interface ProtocolTypes {\n${entries}\n}\n`;
}

function tsType(schema, scope) {
  if (schema === true) {
    return "JsonValue";
  }
  if (schema === false) {
    return "never";
  }
  if (Object.hasOwn(schema, "const")) {
    return literalType(schema.const);
  }
  if (schema.$ref) {
    return refType(schema.$ref, scope);
  }
  if (schema.anyOf) {
    return union(schema.anyOf.map((item) => tsType(item, scope)));
  }
  if (schema.oneOf) {
    return union(schema.oneOf.map((item) => tsType(item, scope)));
  }
  if (Array.isArray(schema.type)) {
    return union(schema.type.map((type) => tsType({ ...schema, type }, scope)));
  }
  if (schema.enum) {
    return union(schema.enum.map((value) => JSON.stringify(value)));
  }

  switch (schema.type) {
    case "null":
      return "null";
    case "boolean":
      return "boolean";
    case "integer":
    case "number":
      return "number";
    case "string":
      return "string";
    case "array":
      return `readonly ${parenthesize(tsType(schema.items ?? true, scope))}[]`;
    case "object":
      return objectType(schema, scope);
    default:
      if (schema.properties || schema.additionalProperties) {
        return objectType(schema, scope);
      }
      return "JsonValue";
  }
}

function literalType(value) {
  if (Array.isArray(value)) {
    return `readonly [${value.map(literalType).join(", ")}]`;
  }
  if (value !== null && typeof value === "object") {
    const keys = Object.keys(value).sort();
    if (keys.length === 0) return "Record<string, never>";
    return `{\n${keys.map(key => `  readonly ${JSON.stringify(key)}: ${literalType(value[key])};`).join("\n")}\n}`;
  }
  return JSON.stringify(value);
}

function objectType(schema, scope) {
  const properties = schema.properties ?? {};
  const required = new Set(schema.required ?? []);
  const lines = Object.keys(properties)
    .sort()
    .map((key) => {
      const optional = required.has(key) ? "" : "?";
      return `  readonly ${JSON.stringify(key)}${optional}: ${tsType(properties[key], scope)};`;
    });
  if (schema.additionalProperties && schema.additionalProperties !== false) {
    lines.push(`  readonly [key: string]: ${tsType(schema.additionalProperties, scope)};`);
  }
  if (lines.length === 0) {
    return "Record<string, JsonValue>";
  }
  return `{\n${lines.join("\n")}\n}`;
}

function refType(ref, scope) {
  const prefix = "#/$defs/";
  if (!ref.startsWith(prefix)) {
    throw new Error(`unsupported non-local ref ${ref} in ${scope}`);
  }
  return defTypeName(scope, ref.slice(prefix.length));
}

function typeName(value) {
  return pascal(value.replace(/\./g, "_"));
}

function defTypeName(scope, value) {
  return `${typeName(scope)}_${pascal(value)}`;
}

function pascal(value) {
  return value
    .replace(/[^a-zA-Z0-9]+/g, "_")
    .split("_")
    .filter(Boolean)
    .map((part) => `${part[0]?.toUpperCase() ?? ""}${part.slice(1)}`)
    .join("");
}

function union(values) {
  return [...new Set(values)].join(" | ");
}

function parenthesize(value) {
  return value.includes(" | ") ? `(${value})` : value;
}
